import { IsString, IsOptional, IsNumber, IsArray, IsDecimal, Min } from 'class-validator';

export class UpdateMenuItemDto {
  @IsOptional()
  @IsString()
  name?: string;

  @IsOptional()
  @IsString()
  description?: string;

  @IsOptional()
  @IsNumber()
  @Min(0)
  price?: number;

  @IsOptional()
  @IsArray()
  @IsNumber({}, { each: true })
  allergen_ids?: number[];
}